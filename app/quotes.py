def _pick(items: tuple[str, ...], day: _dt.date, salt: int = 0) -> str:
    return items[(day.toordinal() + salt) % len(items)]


def greeting(state: str, now: _dt.datetime, lunch_start: _dt.time | None = None,
             overtime_choice: str | None = None, salt: int = 0) -> str:
    """顶部问候语：按时段/状态挑一个短句，同一天不重复。

    salt 是"手动翻页"计数：点一下句子就 +1，从同一天的句子上往后挪一句。
    """
    day = now.date()
    hm = now.hour * 60 + now.minute
    lunch = (lunch_start.hour * 60 + lunch_start.minute) if lunch_start else 12 * 60

    if state == "weekend":
        return _pick(_GREET["weekend"], day, salt)
    if state == "unset":
        return _pick(_GREET["unset"], day, salt)
    if state == "before":
        return _pick(_GREET["before"], day, salt)
    if state == "lunch":
        return _pick(_GREET["lunch"], day, salt)
    if state == "overtime":
        if overtime_choice == "home":
            return _pick(_GREET["home"], day, salt)
        return _pick(_GREET["overtime"], day, salt)
    # 上午 / 午后 / 收尾：按与午休、下班的相对位置分桶
    if hm < lunch - 90:
        return _pick(_GREET["early"], day, salt)
    if hm < lunch - 10:
        return _pick(_GREET["midday"], day, salt)
    if hm < lunch + 150:
        return _pick(_GREET["afternoon"], day, salt)
    return _pick(_GREET["late"], day, salt)


def milestone_text(ratio: float, day: _dt.date) -> str:
    """里程碑那一刻的短语（取最接近的已跨过节点）。"""
    best = None
    for key in sorted(_MILESTONE):
        if ratio + 1e-9 >= key:
            best = key
    if best is None:
        return ""
    return _pick(_MILESTONE[best], day, salt=7)


