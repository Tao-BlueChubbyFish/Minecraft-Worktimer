BUILTIN: tuple[str, ...] = WORK_QUOTES + DEADPAN_QUOTES + GAME_QUOTES

# 洗牌种子：固定值 → 顺序永远一样；改它就能换一整套顺序（周期还是 N 天）。
_SEED = 0x9E3779B9


def _tidy(s: str) -> str:
    """一行显示，句末不留句号（问号、感叹号照旧保留）。"""
    t = " ".join(str(s).split())
    while t.endswith("。"):
        t = t[:-1].rstrip()
    return t


def pool_of(custom=None) -> tuple[str, ...]:
    """用户自定义列表优先；空列表 / 全空白就回落到内置句子。"""
    if isinstance(custom, (list, tuple)):
        items = tuple(_tidy(s) for s in custom if _tidy(s))
        if items:
            return items
    return BUILTIN


@lru_cache(maxsize=8)
def _shuffled(items: tuple[str, ...]) -> tuple[str, ...]:
    """确定性 Fisher-Yates：xorshift32 取随机数，跨 Python 版本结果完全一致。"""
    arr = list(items)
    state = _SEED & 0xFFFFFFFF
    for i in range(len(arr) - 1, 0, -1):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        state &= 0xFFFFFFFF
        j = state % (i + 1)
        arr[i], arr[j] = arr[j], arr[i]
    return tuple(arr)


def for_day(day: _dt.date, custom=None, shuffle: bool = True, salt: int = 0) -> str:
    """按日期取一句：同一天恒定，跨天换下一句，N 天内不重复。

    salt 是"手动翻页"计数：点一下那句话就 +1，从当天这句往后挪一句。
    """
    items = pool_of(custom)
    if shuffle:
        items = _shuffled(items)
    return items[(day.toordinal() + int(salt)) % len(items)]


